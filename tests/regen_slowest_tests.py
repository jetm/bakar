"""Regenerate ``tests/slowest_tests.txt`` from a ``--durations=0`` log of a single-process run.

Usage::

    uv run python tests/regen_slowest_tests.py LOG --source "<where the run happened>" \\
        [--command "<the pytest command>"] [--top 64] [--out tests/slowest_tests.txt]

The log is the output of ``pytest -n 0 --no-cov -p no:randomly --durations=0
--durations-min=0.1 -q`` on an otherwise idle host. A test's wall is the sum of
its setup, call and teardown lines, so a slow fixture counts toward the test that
uses it. Tests whose every phase is under ``--durations-min`` do not appear in the
log and cannot rank.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

DEFAULT_COMMAND = "uv run --no-sync pytest -n 0 --no-cov -p no:randomly --durations=0 --durations-min=0.1 -q"
DEFAULT_TOP = 64

_DURATION_LINE = re.compile(r"^(?P<secs>\d+(?:\.\d+)?)s (?:setup|call|teardown)\s+(?P<nodeid>\S.*?)\s*$")


def rank_slowest(log_text: str, top: int = DEFAULT_TOP) -> list[tuple[str, float]]:
    """Return up to ``top`` ``(nodeid, seconds)`` pairs, longest wall first.

    Ties break on the node id so the output depends only on the log.
    """
    totals: dict[str, float] = defaultdict(float)
    for line in log_text.splitlines():
        match = _DURATION_LINE.match(line)
        if match:
            totals[match["nodeid"]] += float(match["secs"])
    ranked = sorted(totals.items(), key=lambda pair: (-pair[1], pair[0]))
    return ranked[:top]


def render_list(ranked: list[tuple[str, float]], *, command: str, source: str) -> str:
    """Render the list file: a comment header naming the command and the source run, then ids."""
    header = [
        "# Slowest tests first, longest wall first. Read by tests/conftest.py under xdist only.",
        "# Generated by tests/regen_slowest_tests.py; do not edit by hand.",
        f"# Command: {command}",
        f"# Source run: {source}",
        f"# Tests: {len(ranked)}, wall = setup + call + teardown from the log",
    ]
    return "\n".join([*header, *(nodeid for nodeid, _ in ranked)]) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    parser.add_argument("log", type=Path, help="--durations=0 log of a single-process run")
    parser.add_argument("--source", required=True, help="where and when the run happened, for the header")
    parser.add_argument("--command", default=DEFAULT_COMMAND, help="the pytest command that produced the log")
    parser.add_argument("--top", type=int, default=DEFAULT_TOP)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("slowest_tests.txt"))
    args = parser.parse_args(argv)
    ranked = rank_slowest(args.log.read_text(encoding="utf-8"), args.top)
    if not ranked:
        parser.error(f"no duration lines found in {args.log}")
    args.out.write_text(render_list(ranked, command=args.command, source=args.source))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
