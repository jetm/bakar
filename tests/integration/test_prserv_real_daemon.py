"""Host-side integration test for prserv against the real bitbake-prserv daemon.

Skips when no bitbake-prserv is available. Run explicitly with:

    BAKAR_BITBAKE_PRSERV=/path/to/bitbake-prserv \
        uv run pytest tests/integration/test_prserv_real_daemon.py -v --no-cov

The daemon is a double-forked descendant, not a child of the test, so every test
stops what it started in a ``finally``. The state key is chosen so the run does not
depend on whether the host currently holds the port a key derives.
"""

from __future__ import annotations

import os
import shutil
import socket
import stat
import time
from pathlib import Path

import pytest

from bakar import central_service, prserv

_BINARY = "bitbake-prserv"


def _find_real_prserv() -> Path | None:
    candidates: list[Path] = []
    env_override = os.environ.get("BAKAR_BITBAKE_PRSERV")
    if env_override:
        candidates.append(Path(env_override))
    candidates.append(Path.home() / "repos" / "personal" / "yocto" / "bitbake" / "bin" / _BINARY)
    on_path = shutil.which(_BINARY)
    if on_path:
        candidates.append(Path(on_path))
    for c in candidates:
        if c.is_file() and os.access(c, os.X_OK):
            return c
    return None


def _install_workspace_binary(workspace: Path, real_binary: Path) -> None:
    """Install a wrapper at ``sources/poky/bitbake/bin/bitbake-prserv``.

    A bare symlink breaks the script's ``__file__``-relative ``lib/`` lookup, and under
    ``uv run`` the shebang would resolve to the bakar venv interpreter. The wrapper
    unsets ``VIRTUAL_ENV`` and execs the real binary by absolute path with a system PATH.
    """
    workspace_bin_dir = workspace / "sources" / "poky" / "bitbake" / "bin"
    workspace_bin_dir.mkdir(parents=True)
    wrapper = workspace_bin_dir / _BINARY
    wrapper.write_text(
        "#!/usr/bin/env bash\n"
        "# Auto-generated by tests/integration/test_prserv_real_daemon.py\n"
        "unset VIRTUAL_ENV\n"
        f'PATH=/usr/bin:/bin exec {real_binary} "$@"\n'
    )
    wrapper.chmod(wrapper.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _state_key_with_free_port(tmp_path: Path) -> Path:
    for i in range(64):
        key = tmp_path / f"ws{i}"
        port = prserv._workspace_port(key)
        if central_service.bind_conflict("localhost", port) is None and not list(
            Path("/tmp").glob(f"PRServer_*_{port}.pid")
        ):
            return key
    pytest.fail("no state key with a bindable derived port in 64 tries")


def _owned(state_key: Path) -> list[central_service.OwnedDaemon]:
    return central_service.find_owned_daemons(_BINARY, prserv._state_dir(state_key) / prserv._DB_FILENAME)


def _failure(state_key: Path, what: str) -> str:
    msg = f"{what}; derived port {prserv._workspace_port(state_key)}"
    stderr = prserv._state_dir(state_key) / prserv._STDERR_FILENAME
    if stderr.is_file():
        msg += f"; prserv.stderr tail: {stderr.read_text(errors='replace')[-800:]}"
    return msg


def _setup(tmp_path: Path) -> Path:
    real_binary = _find_real_prserv()
    if real_binary is None:
        pytest.skip(
            "bitbake-prserv not available - set BAKAR_BITBAKE_PRSERV or install yocto/bitbake "
            "at ~/repos/personal/yocto/bitbake/bin/bitbake-prserv"
        )
    _install_workspace_binary(tmp_path, real_binary)
    return _state_key_with_free_port(tmp_path)


@pytest.mark.real_home
@pytest.mark.integration
def test_prserv_real_daemon_without_pidfile_is_adopted_and_stopped(tmp_path: Path) -> None:
    state_key = _setup(tmp_path)
    port = prserv._workspace_port(state_key)
    db_file = prserv._state_dir(state_key) / prserv._DB_FILENAME
    try:
        address = prserv.ensure_running(state_key, binary_root=tmp_path)
        assert address == f"localhost:{port}", _failure(state_key, f"ensure_running returned {address!r}")
        assert prserv.is_running(state_key) is True

        pidfiles = list(Path("/tmp").glob(f"PRServer_*_{port}.pid"))
        assert pidfiles, "bitbake-prserv wrote no pidfile for the derived port"
        for pidfile in pidfiles:
            pidfile.unlink()

        again = prserv.ensure_running(state_key, binary_root=tmp_path)
        assert again == address, _failure(state_key, f"ensure_running without pidfile returned {again!r}")
        assert len(_owned(state_key)) == 1, "a second daemon was spawned"
        assert prserv.is_running(state_key) is True

        assert prserv.stop(state_key, binary_root=tmp_path) is True
        for _ in range(50):
            if not _owned(state_key) and not central_service.is_listening("localhost", port):
                break
            time.sleep(0.1)
        assert _owned(state_key) == [], "daemon still present after stop"
        assert central_service.is_listening("localhost", port) is False, "port still answers after stop"
        assert db_file.exists(), "PR database must persist across stop"
    finally:
        prserv.stop(state_key, binary_root=tmp_path)


@pytest.mark.real_home
@pytest.mark.integration
def test_prserv_foreign_listener_on_derived_port_is_refused(tmp_path: Path) -> None:
    state_key = _setup(tmp_path)
    port = prserv._workspace_port(state_key)
    holder = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        holder.bind(("127.0.0.1", port))
        holder.listen(1)

        assert prserv.ensure_running(state_key, binary_root=tmp_path) is None
        assert _owned(state_key) == [], "a daemon was spawned beside a foreign listener"
        stderr = prserv._state_dir(state_key) / prserv._STDERR_FILENAME
        assert stderr.is_file(), "no refusal was recorded"
        assert str(port) in stderr.read_text(errors="replace")
        assert prserv.is_running(state_key) is False
    finally:
        holder.close()
        prserv.stop(state_key, binary_root=tmp_path)
